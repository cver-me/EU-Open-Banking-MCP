// Runs `wrangler dev` with the optional TrueLayer secrets loaded from .dev.vars.
// Wrangler only loads .dev.vars secrets that wrangler.jsonc lists in secrets.required,
// and the TrueLayer ones are optional there so EU-only deployments keep working.
// This writes a gitignored copy of the config that also lists them, then starts dev.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "wrangler.jsonc";
const GENERATED = "wrangler.dev-truelayer.jsonc";
const TRUELAYER_SECRETS = ["TRUELAYER_CLIENT_ID", "TRUELAYER_CLIENT_SECRET", "TOKEN_ENCRYPTION_KEY"];

// wrangler.jsonc uses only whole-line comments.
const config = JSON.parse(
  readFileSync(SOURCE, "utf8").split("\n").filter((line) => !line.trimStart().startsWith("//")).join("\n"),
);
config.secrets ??= {};
config.secrets.required = [...new Set([...(config.secrets.required ?? []), ...TRUELAYER_SECRETS])];
writeFileSync(GENERATED, `// Generated by scripts/dev-truelayer.ts for local development. Do not edit.\n${JSON.stringify(config, null, 2)}\n`);

const result = spawnSync("wrangler", ["dev", "--config", GENERATED, ...process.argv.slice(2)], { stdio: "inherit" });
process.exit(result.status ?? 1);
